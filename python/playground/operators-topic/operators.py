# Python Level 1 — Operators Playground

# ==========================================
# 1. Arithmetic Operators
# ==========================================

a = 15
b = 4

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor division:", a // b)
print("Remainder:", a % b)
print("Power:", a ** b)


# ==========================================
# 2. Real-World Calculation
# ==========================================

price = 500
quantity = 2

total = price * quantity

print(f"Price: {price}")
print(f"Quantity: {quantity}")
print(f"Total: {total}")


# ==========================================
# 3. Comparison Operators
# ==========================================

age = 25

print("Age > 18:", age > 18)
print("Age < 18:", age < 18)
print("Age == 25:", age == 25)
print("Age != 30:", age != 30)


